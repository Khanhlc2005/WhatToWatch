package com.project.movie_recommendation.configuration;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionTemplate;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.GZIPInputStream;

/**
 * Fills {@code genres} and {@code movie_genres} on startup when they are empty, so the Discover genre filter
 * works on any database that holds the catalogue (movies_data.sql only fills {@code movies}).
 * Genre ids are TMDB genre ids; movies are matched by {@code movies.tmdb_id}.
 * The data in {@code resources/seed/} is generated by {@code tools/seed_genres.py}.
 */
@Slf4j
@Component
public class GenreSeeder implements ApplicationRunner {
    private static final int BATCH = 2000;

    private final JdbcTemplate jdbc;
    private final TransactionTemplate tx;
    private final boolean enabled;

    public GenreSeeder(JdbcTemplate jdbc, TransactionTemplate tx,
                       @Value("${app.seed-genres:true}") boolean enabled) {
        this.jdbc = jdbc;
        this.tx = tx;
        this.enabled = enabled;
    }

    @Override
    public void run(ApplicationArguments args) throws Exception {
        if (!enabled) return;
        Long movies = jdbc.queryForObject("SELECT COUNT(*) FROM movies", Long.class);
        Long links = jdbc.queryForObject("SELECT COUNT(*) FROM movie_genres", Long.class);
        if (movies == null || movies == 0 || (links != null && links > 0)) return;

        List<Object[]> genres = new ArrayList<>();
        try (BufferedReader in = reader("seed/genres.csv")) {
            String line;
            while ((line = in.readLine()) != null) {
                int comma = line.indexOf(',');
                if (comma > 0) genres.add(new Object[]{Long.parseLong(line.substring(0, comma)), line.substring(comma + 1)});
            }
        }
        List<long[]> pairs = new ArrayList<>();
        try (BufferedReader in = new BufferedReader(new InputStreamReader(
                new GZIPInputStream(new ClassPathResource("seed/movie_genres.csv.gz").getInputStream()), StandardCharsets.UTF_8))) {
            String line;
            while ((line = in.readLine()) != null) {
                int comma = line.indexOf(',');
                if (comma > 0) pairs.add(new long[]{Long.parseLong(line.substring(0, comma)), Long.parseLong(line.substring(comma + 1))});
            }
        }

        tx.executeWithoutResult(status -> {
            jdbc.batchUpdate("INSERT IGNORE INTO genres (id, name) VALUES (?, ?)", genres);
            jdbc.execute("CREATE TEMPORARY TABLE tmp_movie_genres (tmdb_id BIGINT NOT NULL, genre_id BIGINT NOT NULL)");
            try {
                for (int i = 0; i < pairs.size(); i += BATCH) {
                    StringBuilder sql = new StringBuilder("INSERT INTO tmp_movie_genres VALUES ");
                    for (int j = i; j < Math.min(i + BATCH, pairs.size()); j++) {
                        if (j > i) sql.append(',');
                        sql.append('(').append(pairs.get(j)[0]).append(',').append(pairs.get(j)[1]).append(')');
                    }
                    jdbc.execute(sql.toString());
                }
                jdbc.update("INSERT IGNORE INTO movie_genres (movie_id, genre_id) "
                        + "SELECT m.id, t.genre_id FROM tmp_movie_genres t JOIN movies m ON m.tmdb_id = t.tmdb_id");
            } finally {
                jdbc.execute("DROP TEMPORARY TABLE IF EXISTS tmp_movie_genres");
            }
        });
        log.info("Seeded {} genres and movie-genre links from classpath:seed/", genres.size());
    }

    private static BufferedReader reader(String path) throws java.io.IOException {
        return new BufferedReader(new InputStreamReader(new ClassPathResource(path).getInputStream(), StandardCharsets.UTF_8));
    }
}
